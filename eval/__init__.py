"""评测板块 —— 纯逻辑层，可脱离模型与向量库单测。

为什么要单独成包：
    原 `test_all.py` 把「题集 + 判定 + 画图 + 打接口」全塞在一个脚本里，
    判定口径是「关键词是否出现在答案里」的字符串包含检查。后果：
      · 判定无法单测（改错了没人发现）；
      · 只能测问答，审查/推送零覆盖；
      · 只输出一个总分，无法回答「哪一类题差」。

    这里把「判定（judges）」「指标（metrics）」「数据结构（schema）」
    拆成彼此独立的纯逻辑模块，只依赖标准库，毫秒级可跑完。
    「打服务」这件事交给 runners/，与逻辑解耦。

目录：
    schema.py   —— 题集数据结构与加载器
    judges.py   —— 判定器（关键事实覆盖 / 拒答 / 引用 / 审查三分类 / 规则集合）
    metrics.py  —— 指标（P/R/F1、混淆矩阵、Wilson 置信区间、Kappa、Recall@k、MRR、nDCG）
    cases/      —— 题集数据（JSON）
    runners/    —— 调用服务的执行器（需服务在线）
"""
